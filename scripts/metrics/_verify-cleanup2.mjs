import { MongoClient, dotenv } from './_deps.mjs'
dotenv.config({ path: 'notes-backend/.env' })
const c = await MongoClient.connect(process.env.MONGODB_URI)
const db = c.db('test')
const since = new Date('2026-09-10T09:20:00.000Z')
const mine = await db.collection('assistant_messages').find({ createdAt: { $gte: since } }).project({ requestId: 1, role: 1 }).toArray()
console.log('messages created during my session:', mine.length, JSON.stringify(mine.slice(0, 5)))
const mineConv = await db.collection('assistant_conversations').find({ createdAt: { $gte: since } }).project({ title: 1 }).toArray()
console.log('conversations created during my session:', mineConv.length, JSON.stringify(mineConv.map((x) => String(x.title).slice(0, 20))))
const mineNotes = await db.collection('notes').find({ createdAt: { $gte: since } }).project({ title: 1 }).toArray()
console.log('notes created during my session:', mineNotes.length, JSON.stringify(mineNotes.map((x) => x.title)))
const mineMem = await db.collection('assistant_memories').countDocuments({ createdAt: { $gte: since } })
console.log('memories created during my session:', mineMem)
await c.close()
